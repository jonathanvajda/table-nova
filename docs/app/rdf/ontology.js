/**
 * @file Generate a thin ontology artifact from Table Nova column schemas.
 */
import {
  COMMON_NAMESPACE_IRIS,
  namespacePrefixMapFromRegistry
} from '../shared/namespace-registry/namespace-registry.js';
import { compactIriToCurie, findLongestPrefixMatch } from '../shared/namespace-registry/curie.js';
import {
  appendOntologyMetadataQuads,
  normalizeOntologyMetadataRecord
} from '../shared/ontology-metadata/index.js';
import {
  buildLabelFromWords,
  normalizeStringToCase,
  splitStringToWords
} from '../shared/normalization-utils/index.js';

/**
 * @typedef {import('./schema.js').ColumnSchema} ColumnSchema
 */

const DEFAULT_PREFIXES = {
  ...namespacePrefixMapFromRegistry(),
  tablenova: 'https://example.org/TableNova/',
};

/**
 * Builds ontology Turtle that annotates generated column predicates.
 * @param {ColumnSchema[]} columnSchemas
 * @param {Record<string, string>} prefixes
 * @returns {string}
 */
export function buildOntologyTurtle(columnSchemas, prefixes = DEFAULT_PREFIXES) {
  const activePrefixes = { ...DEFAULT_PREFIXES, ...(prefixes || {}) };
  const prefixText = ['tablenova', 'xsd', 'owl', 'rdfs', 'dcterms']
    .filter((name) => activePrefixes[name])
    .map((name) => `@prefix ${name}: <${activePrefixes[name]}> .`)
    .join('\n');

  const propertyBlocks = (columnSchemas || []).map((schema) => buildPropertyBlock(schema, activePrefixes));
  return `${prefixText}\n\n${propertyBlocks.join('\n\n')}\n`;
}

/**
 * Builds ontology triples as an RDFJS dataset so the T-Box can use the same
 * serializers as instance data.
 * @param {ColumnSchema[]} columnSchemas
 * @param {object} [options]
 * @param {object} [options.metadataRecord] Optional ontology-level metadata to append through the shared writer.
 * @returns {any}
 */
export function buildOntologyDataset(columnSchemas, options = {}) {
  const N3 = /** @type {any} */ (globalThis).N3;
  if (!N3) {
    throw new Error('Global N3 not found. Ensure ./app/shared/vendor/n3.min.js is loaded before Table Nova modules.');
  }

  const { DataFactory, Store } = N3;
  const store = new Store();
  const rdfType = DataFactory.namedNode(COMMON_NAMESPACE_IRIS.rdf.type);
  const datatypeProperty = DataFactory.namedNode(COMMON_NAMESPACE_IRIS.owl.DatatypeProperty);
  const rdfsLabel = DataFactory.namedNode(COMMON_NAMESPACE_IRIS.rdfs.label);
  const rdfsRange = DataFactory.namedNode(COMMON_NAMESPACE_IRIS.rdfs.range);
  const rdfsComment = DataFactory.namedNode(COMMON_NAMESPACE_IRIS.rdfs.comment);
  const dctermsIdentifier = DataFactory.namedNode(COMMON_NAMESPACE_IRIS.dcterms.identifier);

  for (const schema of columnSchemas || []) {
    const subject = DataFactory.namedNode(schema.predicateIri);
    const identifier = schema.originalHeader || schema.key;
    const comment = `Generated by Table Nova from source column '${identifier}'.`;

    store.addQuad(subject, rdfType, datatypeProperty);
    store.addQuad(subject, rdfsLabel, DataFactory.literal(String(schema.label || '')));
    store.addQuad(subject, rdfsRange, DataFactory.namedNode(schema.datatypeIri));
    store.addQuad(subject, dctermsIdentifier, DataFactory.literal(String(identifier || '')));
    store.addQuad(subject, rdfsComment, DataFactory.literal(comment));
  }

  if (options.metadataRecord) {
    appendOntologyMetadataQuads(store, options.metadataRecord);
  }

  return store;
}

/**
 * Builds self-describing ontology metadata for a Table Nova-generated TBox.
 *
 * The result is the canonical full-IRI JSON-LD-compatible metadata record used
 * by the shared ontology metadata package. The source is intentionally limited
 * to the local filename so exported RDF does not leak a user's filesystem path.
 *
 * @param {object} params
 * @param {string} params.filename Local source filename.
 * @param {string} params.createdAtIso ISO timestamp for the transformation run.
 * @param {string} params.runId Stable run identifier recorded in project storage.
 * @param {string} [params.baseOntologyIri='https://example.org/TableNova/'] Base IRI for generated ontology documents.
 * @param {string} [params.localNameStyle='PascalCase'] Local-name style for the generated ontology IRI.
 * @param {string} [params.language='en'] Language tag for generated literals.
 * @param {string|string[]} [params.creator] Optional user/profile creator value(s).
 * @param {string|string[]} [params.contributors] Optional user/profile contributor value(s).
 * @param {string} [params.outputMimeType] Optional MIME type for a specific serialized export.
 * @returns {object} Canonical ontology metadata record.
 */
export function buildTableNovaOntologyMetadataRecord({
  filename,
  createdAtIso,
  runId,
  baseOntologyIri = DEFAULT_PREFIXES.tablenova,
  localNameStyle = 'PascalCase',
  language = 'en',
  creator,
  contributors,
  outputMimeType
} = {}) {
  const sourceFileName = getLocalFileName(filename);
  const title = buildGeneratedOntologyTitle(sourceFileName);
  const localName = normalizeStringToCase(title, localNameStyle, { fallbackStyle: 'PascalCase' }) || 'GeneratedTableNovaSchema';
  const base = ensurePathIriBase(baseOntologyIri);
  const timestamp = normalizeIsoTimestampForIri(createdAtIso);
  const creatorValues = [
    ...asNonEmptyArray(creator),
    'Generated by Table-Nova'
  ];

  return normalizeOntologyMetadataRecord({
    '@id': `${base}${localName}`,
    [COMMON_NAMESPACE_IRIS.owl.versionIRI]: `${base}${timestamp}/${localName}`,
    [COMMON_NAMESPACE_IRIS.owl.versionInfo]: createdAtIso,
    [COMMON_NAMESPACE_IRIS.dcterms.created]: createdAtIso,
    [COMMON_NAMESPACE_IRIS.dcterms.modified]: createdAtIso,
    [COMMON_NAMESPACE_IRIS.dcterms.title]: { '@value': title, '@language': language || 'en' },
    [COMMON_NAMESPACE_IRIS.dcterms.description]: {
      '@value': buildGeneratedOntologyDescription({
        sourceFileName,
        createdAtIso,
        creatorText: asNonEmptyArray(creator)[0] || 'null'
      }),
      '@language': language || 'en'
    },
    [COMMON_NAMESPACE_IRIS.dcterms.source]: sourceFileName,
    [COMMON_NAMESPACE_IRIS.dcterms.format]: outputMimeType || undefined,
    [COMMON_NAMESPACE_IRIS.dcterms.creator]: creatorValues,
    [COMMON_NAMESPACE_IRIS.dcterms.contributor]: asNonEmptyArray(contributors),
    [COMMON_NAMESPACE_IRIS.okea.hasGeneratingSoftwareApplicationName]: 'Table-Nova',
    [COMMON_NAMESPACE_IRIS.okea.hasGenerationRunIdentifier]: runId,
    [COMMON_NAMESPACE_IRIS.okea.hasOntologyBaseIri]: base,
    [COMMON_NAMESPACE_IRIS.okea.hasIriPolicyModeTextValue]: 'readable',
    [COMMON_NAMESPACE_IRIS.okea.hasIriLocalNameDelimiterTextValue]: '/',
    [COMMON_NAMESPACE_IRIS.okea.hasIriLocalNameStyleTextValue]: localNameStyle,
    [COMMON_NAMESPACE_IRIS.okea.hasIriVersionTokenStrategyTextValue]: 'datetime',
    [COMMON_NAMESPACE_IRIS.okea.hasIriVersionInsertionPositionTextValue]: 'infix',
    language
  });
}

/**
 * Converts ontology dataset quads into Table Nova display/storage records.
 * @param {any} dataset
 * @returns {Array<{s: string, p: string, g: string, oType: 'iri'|'literal', oValue: string, datatypeIri?: string, lang?: string}>}
 */
export function ontologyRecordsFromDataset(dataset) {
  const quads = dataset?.getQuads ? dataset.getQuads(null, null, null, null) : [];
  return quads.map((q) => {
    const base = {
      s: q.subject.value,
      p: q.predicate.value,
      g: q.graph?.termType === 'DefaultGraph' ? '' : q.graph?.value || ''
    };
    if (q.object.termType === 'NamedNode') {
      return { ...base, oType: 'iri', oValue: q.object.value };
    }
    return {
      ...base,
      oType: 'literal',
      oValue: q.object.value,
      datatypeIri: q.object.datatype?.value,
      lang: q.object.language || undefined
    };
  });
}

/**
 * @param {ColumnSchema} schema
 * @param {Record<string, string>} prefixes
 * @returns {string}
 */
export function buildPropertyBlock(schema, prefixes) {
  const subject = compactIri(schema.predicateIri, prefixes);
  const range = compactIri(schema.datatypeIri, prefixes);
  const identifier = schema.originalHeader || schema.key;
  const comment = `Generated by Table Nova from source column '${identifier}'.`;

  return `${subject} a owl:DatatypeProperty ;\n` +
    `  rdfs:label "${escapeTurtleLiteral(schema.label)}" ;\n` +
    `  rdfs:range ${range} ;\n` +
    `  dcterms:identifier "${escapeTurtleLiteral(identifier)}" ;\n` +
    `  rdfs:comment "${escapeTurtleLiteral(comment)}" .`;
}

/**
 * Compacts an IRI to a prefixed name when possible.
 * @param {string} iri
 * @param {Record<string, string>} prefixes
 * @returns {string}
 */
export function compactIri(iri, prefixes = DEFAULT_PREFIXES) {
  const value = String(iri ?? '');
  const compacted = compactIriToCurie(value, prefixes);
  if (compacted.ok) return compacted.value;

  const match = findLongestPrefixMatch(value, prefixes);
  if (match.ok) {
    const local = value.slice(String(match.namespaceIri).length);
    if (/^[A-Za-z_][A-Za-z0-9_-]*$/.test(local)) return `${match.prefix}:${local}`;
  }
  return `<${value.replace(/>/g, '%3E')}>`;
}

/**
 * Escapes a literal for Turtle output.
 * @param {string} value
 * @returns {string}
 */
export function escapeTurtleLiteral(value) {
  return String(value ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n');
}

function buildGeneratedOntologyTitle(filename) {
  const stem = getLocalFileName(filename).replace(/\.[^.]+$/, '');
  const words = splitStringToWords(stem);
  const label = buildLabelFromWords(words, { fallback: 'Generated Table Nova' });
  return /\bschema\b/i.test(label) ? label : `${label} Schema`;
}

function buildGeneratedOntologyDescription({ sourceFileName, createdAtIso, creatorText }) {
  return `This data schema was automatically generated by Table-Nova, from a tabular dataset ${sourceFileName || 'unknown source file'} on ${createdAtIso || 'an unknown datetime'}, guided by input from the user ${creatorText || 'null'}. It is, in effect, a 'naive' ontology of the data, and is not purported to be a robust account of a domain on its own. Use at your own risk.`;
}

function getLocalFileName(filename) {
  const text = String(filename || 'source-file.csv').trim();
  return text.split(/[\\/]/).filter(Boolean).pop() || 'source-file.csv';
}

function normalizeIsoTimestampForIri(value) {
  const date = new Date(value || Date.now());
  const iso = Number.isFinite(date.getTime()) ? date.toISOString() : new Date(0).toISOString();
  return iso.replace(/\.\d{3}Z$/, 'Z').replace(/:/g, '-');
}

function ensurePathIriBase(iri) {
  return String(iri || DEFAULT_PREFIXES.tablenova).replace(/[?#]+$/g, '').replace(/\/?$/, '/');
}

function asNonEmptyArray(value) {
  const items = Array.isArray(value) ? value : [value];
  return items.map((item) => String(item || '').trim()).filter(Boolean);
}
